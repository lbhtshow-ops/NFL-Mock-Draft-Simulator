import assert from "node:assert/strict";
import { buildDraftResultSnapshot, validateDraftResultSnapshot } from "./DraftResultSnapshot.js";
import { buildDraftResultApplicationView } from "./applicationView.js";
import { draftResultsFixture } from "./fixture.js";
import { draftRoomFixture } from "../sprint2B_2/fixture.js";

const { snapshot, view, finalizedState } = draftResultsFixture;
assert.equal(validateDraftResultSnapshot(snapshot).valid, true);
assert.equal(snapshot.resultStatus, "PARTIAL_FIXTURE_RESULT");
assert.equal(snapshot.fixtureOnly, true);
assert.equal(snapshot.persisted, false);
assert.equal(snapshot.shareable, false);
assert.equal(snapshot.productionResult, false);
assert.equal(snapshot.totalSelections, 1);
assert.equal(snapshot.userSelectionCount, 1);
assert.equal(snapshot.selections[0].selectionOrder, 1);
assert.equal(snapshot.completeHistory[0].prospectDisplayName, finalizedState.history[0].prospectDisplayNameSnapshot);
assert.equal(snapshot.userDraftClass.selections.length, 1);
assert.equal(Object.values(snapshot.userDraftClass.positionDistribution).reduce((a, b) => a + b, 0), 1);
assert.equal(Object.isFrozen(snapshot), true);
assert.equal(Object.isFrozen(snapshot.selections[0]), true);
assert.equal(view.status, "READY");
assert.equal(view.header.savedStatus, "NOT_SAVED");
assert.equal(view.header.shareStatus, "NOT_SHAREABLE");
assert(!/(letterGrade|starRating|teamFitScore|schemeFitScore|draftIntelligenceScore)/i.test(JSON.stringify(snapshot)));
const rebuilt = buildDraftResultSnapshot({ state: finalizedState, sourceProspects: draftRoomFixture.prospects.all, suppliedCompletedAtRef: "fixture-step:2" });
assert.deepEqual(rebuilt, snapshot);
assert.deepEqual(buildDraftResultApplicationView(rebuilt), view);
const invalid = buildDraftResultApplicationView({});
assert.equal(invalid.status, "INVALID_RESULT");
console.log(JSON.stringify({ suite: "DraftResultsCenterDiagnostics", passed: true, checks: 20, resultStatus: snapshot.resultStatus, selectionCount: snapshot.totalSelections, deterministic: true, immutable: true, persisted: false, shareable: false }, null, 2));
