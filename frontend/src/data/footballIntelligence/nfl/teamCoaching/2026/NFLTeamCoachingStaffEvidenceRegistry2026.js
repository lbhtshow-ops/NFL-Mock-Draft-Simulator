const normalizeTeam = (team) =>
  typeof team === "string" && team.trim() ? team.trim().toUpperCase() : null;

function toObservation(team, source, member) {
  return Object.freeze({
    domain: "COACHING",
    subject: member.role,
    role: member.role,
    value: member.displayName,
    displayName: member.displayName,
    title: member.title,
    classification: "FACT",
    sourceId: source.sourceId,
    sourceType: "OFFICIAL_CLUB",
    sourceLabel: source.sourceLabel,
    sourceUri: source.sourceUri,
    observedAt: VERIFIED_AT,
    verifiedAt: VERIFIED_AT,
    effectiveFrom: EFFECTIVE_FROM,
    confidence: 1,
    notes: `Official 2026 ${team} coaching-staff listing; exact club title preserved.`,
  });
}

export function getNFLTeamCoachingStaffEvidenceInput2026(input = {}) {
  const normalizedInput =
    typeof input === "string" ? { team: input, season: 2026 } : input || {};
  const team = normalizeTeam(normalizedInput.team);
  const season = Number.isInteger(normalizedInput.season) ? normalizedInput.season : 2026;
  const asOf =
    typeof normalizedInput.asOf === "string" && normalizedInput.asOf.trim()
      ? normalizedInput.asOf.trim()
      : VERIFIED_AT;

  const source = season === 2026 && team ? TEAM_DATA[team] : null;
  const observations = source
    ? Object.freeze(source.staff.map((member) => toObservation(team, source, member)))
    : Object.freeze([]);

  return Object.freeze({
    registryVersion: NFL_TEAM_COACHING_STAFF_EVIDENCE_REGISTRY_2026_VERSION,
    team,
    season,
    asOf,
    status: observations.length ? "AVAILABLE" : "UNAVAILABLE",
    observations,
  });
}

export function mergeNFLTeamCoachingStaffEvidence2026(input = {}) {
  const registry = getNFLTeamCoachingStaffEvidenceInput2026(input);
  const supplied = Array.isArray(input?.observations) ? input.observations : [];

  if (registry.season !== 2026 || registry.observations.length === 0) {
    return input;
  }

  return Object.freeze({
    ...input,
    team: registry.team,
    season: registry.season,
    asOf: input?.asOf || registry.asOf,
    observations: Object.freeze([...registry.observations, ...supplied]),
  });
}

export function listNFLTeamCoachingStaffEvidenceTeams2026() {
  return Object.freeze(Object.keys(TEAM_DATA));
}

